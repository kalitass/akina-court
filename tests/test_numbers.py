"""The committed submission summary and the README must carry the numbers the benchmark files hold.

web/submission.json is generated by scripts/build_submission.py from bench/results/; this test rebuilds it in memory
and compares. The README is hand-written, so only its load-bearing figures are checked against the same sources.
"""
import json
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import build_submission  # noqa: E402


@pytest.fixture(scope="module")
def built():
    return build_submission.build()


def test_submission_json_matches_benchmark_files(built):
    committed = json.loads((ROOT / "web" / "submission.json").read_text())
    for d in (built, committed):
        d.pop("generated_at", None)
    assert committed == built, "web/submission.json is stale: run python scripts/build_submission.py"


def test_readme_numbers_match_benchmark_files(built):
    readme = (ROOT / "README.md").read_text()
    p = built["provenance"]
    court = next(m for m in built["metrics"] if m["name"] == "invalid citations")
    total_cites = int(re.search(r"of ([\d,]+)", court["value"]).group(1).replace(",", ""))
    n_tests = int(re.match(r"(\d+) automated tests", built["boundaries"]["real"][-1]).group(1))
    expect = [
        f"{n_tests} tests",
        f"{p['stored_runs']} stored case-system runs",
        f"{p['recorded_model_calls']:,} recorded model calls",
        f"{p['input_tokens_total']/1e6:.1f} M input tokens",
        f"{p['audit_sample']['http_calls']} HTTP calls",
        f"0 invalid citations in {total_cites}",
        p["benchmark_window_utc"].replace(" to ", " to ").split(" UTC")[0][:10],
    ]
    missing = [e for e in expect if e not in readme]
    assert not missing, f"README.md does not carry: {missing}"
    wrong = next(m for m in built["metrics"] if m["name"] == "wrong core decisions that would execute")
    assert wrong["value"].startswith("0/"), wrong
