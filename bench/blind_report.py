#!/usr/bin/env python3
"""Score the held-out (blind) set: bench/results/blind/<arm>/X-*.json against data/bench/blind/manifest.json.

    .venv/bin/python bench/blind_report.py        # table per arm and per case -> bench/results/blind/summary.md

Same core-decision rule as bench/report.py (outcome + amount to the cent + escalation flag). The blind cases were
written after the prompts were frozen and never used to tune them; the result is reported as it comes.
"""
from __future__ import annotations

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAN = ROOT / "data" / "bench" / "blind" / "manifest.json"
RES = ROOT / "bench" / "results" / "blind"


def exact(rul: dict, t: dict) -> bool:
    if bool(rul.get("escalate")) != bool(t["escalate"]):
        return False
    if t["escalate"]:
        return True
    if rul.get("ruling") != t["ruling"]:
        return False
    a, b = float(rul.get("amount") or 0), float(t.get("amount") or 0)
    return abs(round(a * 100) - round(b * 100)) <= 1


def main() -> int:
    man = json.loads(MAN.read_text())
    truth = {c["case_id"]: c for c in man["cases"]}
    lines = ["# Blind set (held out)", "", f"Reference version: {man['reference_version']}", f"Generated by: {man['generated_by']}", ""]
    arms = sorted(p.name for p in RES.iterdir() if p.is_dir()) if RES.exists() else []
    for arm in arms:
        rows = []
        files = [f for f in sorted(glob.glob(str(RES / arm / "X-*.json"))) if not f.endswith(".record.json") and ".r" not in Path(f).name[6:]]
        for f in files:                       # one result file per case; *.record.json is the full court record, not a result
            d = json.loads(Path(f).read_text())
            cid = d["case_id"]; t = truth[cid]["truth"]; r = d.get("ruling") or {}
            failed = not d.get("ok")
            ok = (not failed) and exact(r, t)
            wrong_exec = (not failed) and (not ok) and not r.get("escalate")   # a wrong ruling the court let through; a failed run is not one
            rows.append((cid, truth[cid]["name"], f"{t['ruling']}{' $%.2f' % t['amount'] if t.get('amount') else ''}",
                         (f"run failed: {str(d.get('error', ''))[:60]}" if failed else f"{r.get('ruling')}{' $%.2f' % r['amount'] if r.get('amount') else ''}"),
                         "—" if failed else ("yes" if ok else "no"), "YES" if wrong_exec else "", (r.get("evidence_gap") or r.get("escalation_reason") or "")[:140]))
        assert len({r[0] for r in rows}) == len(rows), "a case is counted twice"
        n_ok = sum(1 for r in rows if r[4] == "yes"); n_wx = sum(1 for r in rows if r[5]); n_fail = sum(1 for r in rows if r[4] == "—")
        lines += [f"## {arm}: core decision {n_ok}/{len(rows)}, wrong and executed {n_wx}/{len(rows)}, runs failed {n_fail}/{len(rows)}", "",
                  "| case | scenario | reference | model | match | wrong & executed | model's ground |", "|---|---|---|---|---|---|---|"]
        lines += ["| " + " | ".join(str(x).replace("|", "/") for x in r) + " |" for r in rows]
        lines.append("")
    out = "\n".join(lines)
    (RES / "summary.md").write_text(out) if RES.exists() else None
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
